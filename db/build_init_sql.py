#!/usr/bin/env python3
"""Generate the Postgres container's first-boot init SQL from the migrations and
the seed data.

The Postgres image runs `db/init/*.sql` once, in order, on an empty data volume
(see docker-compose.yml). This writes two generated files there so a fresh
`docker compose up -d` comes up fully populated — schema + the whole catalog —
with no manual migrate/seed step:

  * `db/init/01_schema.sql`  — the migrations concatenated, in order.
  * `db/init/02_seed.sql`    — all books (curated + KB catalog), the demo admin
                               user, its ratings and its shelves.

Both are GENERATED. Re-run this after changing a migration, the seed data, or
`kb_catalog.json`, then recreate the volume to apply:
    python db/build_catalog_from_kb.py      # refresh kb_catalog.json (needs AWS)
    python db/build_init_sql.py
    docker compose down -v && docker compose up -d

The host-run path (`python db/migrate.py && python db/seed.py`) still works and
reads the same data; this only mirrors it into container-init SQL.
"""
from __future__ import annotations

import json
from pathlib import Path

DB_DIR = Path(__file__).resolve().parent
INIT_DIR = DB_DIR / "init"
MIGRATIONS = DB_DIR / "migrations"
SEED = json.loads((DB_DIR / "seed_data.json").read_text(encoding="utf-8"))
KB = json.loads((DB_DIR / "kb_catalog.json").read_text(encoding="utf-8")) if (DB_DIR / "kb_catalog.json").is_file() else {"books": []}

ADMIN_EMAIL = SEED["admin_user"]["email"]
GEN_HEADER = "-- GENERATED by db/build_init_sql.py — do not edit by hand.\n"
_COLS = "isbn, title, authors, description, pages, published_year, language, genres, cover_url, source"
_RECORD = ("x(isbn text, title text, authors text[], description text, pages int, "
           "published_year int, language text, genres text[], cover_url text, source text)")
_OVERWRITE = ", ".join(
    f"{c} = EXCLUDED.{c}" for c in
    "title authors description pages published_year language genres cover_url source".split()
)


def lit(value) -> str:
    """A SQL string literal (or NULL)."""
    if value is None:
        return "NULL"
    return "'" + str(value).replace("'", "''") + "'"


def _norm(book: dict, default_source: str) -> dict:
    isbn = book["isbn"]
    return {
        "isbn": isbn,
        "title": book["title"],
        "authors": book.get("authors") or [],
        "description": book.get("description"),
        "pages": book.get("pages"),
        "published_year": book.get("published_year"),
        "language": book.get("language"),
        "genres": book.get("genres") or [],
        "cover_url": book.get("cover_url") or f"https://covers.openlibrary.org/b/isbn/{isbn}-L.jpg",
        "source": book.get("source") or default_source,
    }


def _books_insert(books: list[dict], default_source: str, on_conflict: str) -> str:
    rows = json.dumps([_norm(b, default_source) for b in books], ensure_ascii=False)
    # Dollar-quoted so nothing in the JSON needs escaping.
    return (
        f"INSERT INTO books ({_COLS})\n"
        f"SELECT {_COLS}\n"
        f"FROM jsonb_to_recordset($bookdata${rows}$bookdata$::jsonb) AS {_RECORD}\n"
        f"{on_conflict};\n"
    )


def build_schema() -> str:
    parts = [GEN_HEADER, "-- Schema: every migration in order (see db/migrations/).\n"]
    for sql in sorted(MIGRATIONS.glob("*.sql")):
        parts.append(f"\n-- ===== {sql.name} =====\n")
        parts.append(sql.read_text(encoding="utf-8").rstrip() + "\n")
    return "".join(parts)


def build_seed() -> str:
    out = [GEN_HEADER, "-- Seed: catalog (curated + KB), demo admin user, ratings, shelves.\n\n"]

    out.append("-- Books: curated first (keep their descriptions), then the KB catalog\n")
    out.append("-- (authoritative — overwrites on an ISBN conflict).\n")
    out.append(_books_insert(SEED.get("books", []), "openlibrary", "ON CONFLICT (isbn) DO NOTHING"))
    out.append("\n")
    out.append(_books_insert(KB.get("books", []), "bedrock-kb", f"ON CONFLICT (isbn) DO UPDATE SET {_OVERWRITE}"))

    # Admin user — the users trigger (migration 0004) creates its Exclusion shelf.
    admin = SEED["admin_user"]
    out.append("\n-- Demo admin user (its Exclusion shelf is created by a trigger).\n")
    out.append(
        f"INSERT INTO users (email, display_name) VALUES "
        f"({lit(ADMIN_EMAIL)}, {lit(admin.get('display_name', 'Admin'))}) "
        f"ON CONFLICT (email) DO NOTHING;\n"
    )
    if admin.get("password_hash"):
        out.append(
            f"INSERT INTO user_details (user_id, password_hash)\n"
            f"  SELECT user_id, {lit(admin['password_hash'])} FROM users WHERE email = {lit(ADMIN_EMAIL)}\n"
            f"  ON CONFLICT (user_id) DO NOTHING;\n"
        )

    ratings = SEED.get("ratings", [])
    if ratings:
        out.append("\n-- Ratings / reviews.\n")
        for r in ratings:
            rating_sql = "NULL" if r.get("rating") is None else str(int(r["rating"]))
            out.append(
                f"INSERT INTO user_library (user_id, book_id, rating, review)\n"
                f"  SELECT u.user_id, b.book_id, {rating_sql}, {lit(r.get('review'))}\n"
                f"  FROM users u, books b WHERE u.email = {lit(ADMIN_EMAIL)} AND b.isbn = {lit(r['isbn'])}\n"
                f"  ON CONFLICT (user_id, book_id) DO NOTHING;\n"
            )

    shelves = SEED.get("shelves", [])
    normal = [s for s in shelves if s["name"].strip().lower() != "exclusion"]
    exclusion = [s for s in shelves if s["name"].strip().lower() == "exclusion"]

    if normal:
        out.append("\n-- Named shelves.\n")
        for s in normal:
            out.append(
                f"INSERT INTO shelves (user_id, name)\n"
                f"  SELECT user_id, {lit(s['name'])} FROM users WHERE email = {lit(ADMIN_EMAIL)}\n"
                f"  ON CONFLICT DO NOTHING;\n"
            )

    out.append("\n-- Shelf memberships (normal shelves first, then Exclusion).\n")
    for s in normal:
        for isbn in s.get("books", []):
            out.append(
                f"INSERT INTO shelf_books (shelf_id, book_id)\n"
                f"  SELECT s.shelf_id, b.book_id FROM shelves s JOIN users u ON u.user_id = s.user_id, books b\n"
                f"  WHERE u.email = {lit(ADMIN_EMAIL)} AND lower(s.name) = lower({lit(s['name'])}) AND b.isbn = {lit(isbn)}\n"
                f"  ON CONFLICT DO NOTHING;\n"
            )
    for s in exclusion:
        for isbn in s.get("books", []):
            out.append(
                f"INSERT INTO shelf_books (shelf_id, book_id)\n"
                f"  SELECT s.shelf_id, b.book_id FROM shelves s JOIN users u ON u.user_id = s.user_id, books b\n"
                f"  WHERE u.email = {lit(ADMIN_EMAIL)} AND s.is_exclusion AND b.isbn = {lit(isbn)}\n"
                f"  ON CONFLICT DO NOTHING;\n"
            )
    return "".join(out)


def main() -> int:
    INIT_DIR.mkdir(exist_ok=True)
    (INIT_DIR / "01_schema.sql").write_text(build_schema(), encoding="utf-8", newline="\n")
    (INIT_DIR / "02_seed.sql").write_text(build_seed(), encoding="utf-8", newline="\n")
    print(f"Wrote db/init/01_schema.sql ({len(list(MIGRATIONS.glob('*.sql')))} migrations)")
    print(f"Wrote db/init/02_seed.sql  ({len(SEED.get('books', []))} curated + {len(KB.get('books', []))} KB books)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
